//! Controller input through the InputPlumber daemon: it owns the physical controllers, gives
//! games one virtual pad, and sends everything to Hearth over D-Bus while Hearth's own screens
//! are shown, so menu presses never reach a game. See `docs/spikes/inputplumber.md`.
//!
//! - Hearth in front ([`InputMode::Shell`]): `InterceptMode` Always, menu profile.
//! - Game in front ([`InputMode::Game`]): the game's profile, then Pass. A Guide press switches
//!   the controller back to Always by itself and arrives here.
//!
//! Hearth sets `ManageAllDevices` while it runs (InputPlumber leaves external controllers alone
//! otherwise) and hands everything back on exit ([`release_all`]).

pub mod client;

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};
use std::sync::mpsc::{self, Receiver, RecvTimeoutError, Sender};
use std::thread;
use std::time::{Duration, Instant};

use zbus::MatchRule;
use zbus::blocking::MessageIterator;
use zbus::message::Type as MessageType;

use self::client::{Client, ClientError, InterceptMode, SERVICE};
use super::pad_state::{PadEvent, PadState};
use super::{Action, InputBackend, InputCommand, InputControl, InputError, InputMode, PadActivity};

/// The one virtual controller games see: an Xbox Elite 2 pad, whose four paddles and Share
/// button carry emulator actions (SDL and RetroArch both see them).
pub const VIRTUAL_PAD: &str = "xbox-elite";
/// D-Bus event names Hearth's profiles send for inputs InputPlumber has no `ui_*` name for.
pub const TOUCHPAD_EVENT: &str = "hearth_touchpad";
/// Sent while a game runs by the button bound to Hearth's Capture.
pub const CAPTURE_EVENT: &str = "hearth_capture";

/// Hearth's menu profile: buttons unchanged, the touchpad click sent to Hearth (InputPlumber
/// drops it over D-Bus otherwise). Loaded whenever Hearth is in front, so a game's remapping
/// never changes Hearth's own buttons.
pub const MENU_PROFILE: &str = "\
# Generated by Hearth: its menus, every button unchanged.
version: 1
kind: DeviceProfile
name: Hearth menus
mapping:
  - name: Touchpad click
    source_event:
      touchpad:
        name: CenterPad
        touch:
          button: Press
    target_events:
      - dbus: hearth_touchpad
";

/// Longest sleep without an event or a pending deadline.
const IDLE_WAIT: Duration = Duration::from_millis(250);
/// How often controllers are listed again (battery, missed signals).
const DEVICES_REFRESH: Duration = Duration::from_secs(10);

/// Controller input via InputPlumber, on its own thread.
#[derive(Debug)]
pub struct InputPlumberBackend {
    client: Client,
    activity: PadActivity,
    menu_profile: PathBuf,
    commands: Sender<InputCommand>,
    pending: Option<Receiver<InputCommand>>,
}

impl InputPlumberBackend {
    /// Connects to the daemon and takes the controllers (`ManageAllDevices`). Fails if the
    /// daemon isn't running, is too old, or refuses the write (polkit). `runtime_dir` receives
    /// the menu profile (the root daemon reads it from there).
    pub fn connect(runtime_dir: &Path) -> Result<Self, ClientError> {
        let client = Client::connect()?;
        let menu_profile = runtime_dir.join("menu.yaml");
        std::fs::create_dir_all(runtime_dir)
            .and_then(|()| std::fs::write(&menu_profile, MENU_PROFILE))
            .map_err(|err| ClientError::DBus(format!("writing the menu profile: {err}")))?;
        client.set_manage_all(true)?;
        let (commands, pending) = mpsc::channel();
        Ok(Self {
            client,
            activity: PadActivity::new(),
            menu_profile,
            commands,
            pending: Some(pending),
        })
    }

    /// Live controller state (connected pads, held inputs).
    pub fn activity(&self) -> PadActivity {
        self.activity.clone()
    }

    /// The session's handle: mode switches, game profiles, release on exit.
    pub fn control(&self) -> InputControl {
        InputControl::new(self.commands.clone())
    }
}

impl InputBackend for InputPlumberBackend {
    fn start(&mut self, tx: Sender<Action>) -> Result<(), InputError> {
        let commands = self.pending.take().ok_or(InputError::AlreadyStarted)?;
        let (msg_tx, msg_rx) = mpsc::channel();
        // Signals first, so no controller created from now on is missed.
        let signals = subscribe(&self.client).map_err(|err| InputError::Start(err.to_string()))?;
        let signal_tx = msg_tx.clone();
        thread::Builder::new()
            .name("hearth-ip-signals".into())
            .spawn(move || forward_signals(signals, &signal_tx))
            .map_err(|err| InputError::Start(err.to_string()))?;
        thread::Builder::new()
            .name("hearth-ip-commands".into())
            .spawn(move || {
                for command in commands {
                    if msg_tx.send(Msg::Command(command)).is_err() {
                        return;
                    }
                }
            })
            .map_err(|err| InputError::Start(err.to_string()))?;
        let mut worker = Worker {
            client: self.client.clone(),
            activity: self.activity.clone(),
            menu_profile: self.menu_profile.clone(),
            game_profile: None,
            mode: InputMode::Shell,
            devices: BTreeSet::new(),
            ignored: BTreeSet::new(),
            released: false,
            state: PadState::default(),
            pressed: Vec::new(),
        };
        worker.refresh_devices();
        thread::Builder::new()
            .name("hearth-inputplumber".into())
            .spawn(move || worker.run(&msg_rx, &tx))
            .map_err(|err| InputError::Start(err.to_string()))?;
        Ok(())
    }
}

/// Hands every controller back to the system: input to its virtual pad, default profile, and
/// external controllers released (`ManageAllDevices` off). Uses its own connection, so it works
/// from a panic hook or another process (the guard) whatever state the backend is in.
pub fn release_all() -> Result<(), ClientError> {
    let client = Client::connect()?;
    release_devices(&client, &client.composite_devices()?);
    client.set_manage_all(false)
}

fn release_devices<'a>(client: &Client, devices: impl IntoIterator<Item = &'a String>) {
    for device in devices {
        if let Err(err) = client.release(device) {
            tracing::warn!(%device, "handing the controller back failed: {err}");
        }
    }
}

/// Everything the worker thread reacts to.
#[derive(Debug)]
enum Msg {
    Command(InputCommand),
    /// `InputEvent(name, value)` from a D-Bus target.
    Input(String, f64),
    /// Composite devices were added or removed.
    Devices,
}

/// Every signal the daemon sends (input events, devices coming and going).
fn subscribe(client: &Client) -> Result<MessageIterator, zbus::Error> {
    let rule = MatchRule::builder()
        .msg_type(MessageType::Signal)
        .sender(SERVICE)?
        .build();
    MessageIterator::for_match_rule(rule, client.connection(), Some(64))
}

fn forward_signals(signals: MessageIterator, tx: &Sender<Msg>) {
    for message in signals {
        let Ok(message) = message else {
            continue;
        };
        let header = message.header();
        let (Some(interface), Some(member)) = (header.interface(), header.member()) else {
            continue;
        };
        let msg = match (interface.as_str(), member.as_str()) {
            ("org.shadowblip.Input.DBusDevice", "InputEvent") => {
                match message.body().deserialize::<(String, f64)>() {
                    Ok((name, value)) => Msg::Input(name, value),
                    Err(err) => {
                        tracing::debug!("bad InputEvent: {err}");
                        continue;
                    }
                }
            }
            ("org.freedesktop.DBus.ObjectManager", "InterfacesAdded" | "InterfacesRemoved") => {
                Msg::Devices
            }
            _ => continue,
        };
        if tx.send(msg).is_err() {
            return;
        }
    }
    tracing::warn!("InputPlumber signal stream ended");
}

/// Hearth pad position name of an InputPlumber D-Bus event. D-pad and left stick both send
/// `ui_up`… (InputPlumber merges them), so both count as the D-pad here.
fn position_of(event: &str) -> Option<&'static str> {
    Some(match event {
        "ui_accept" => "south",
        "ui_back" => "east",
        "ui_action" => "west",
        "ui_context" => "north",
        "ui_l1" => "l1",
        "ui_r1" => "r1",
        "ui_l2" => "l2",
        "ui_r2" => "r2",
        "ui_l3" => "l3",
        "ui_r3" => "r3",
        "ui_option" => "start",
        "ui_select" => "select",
        "ui_guide" => "guide",
        "ui_up" => "dpad_up",
        "ui_down" => "dpad_down",
        "ui_left" => "dpad_left",
        "ui_right" => "dpad_right",
        "ui_volume_mute" => "mute",
        TOUCHPAD_EVENT => "touchpad",
        _ => return None,
    })
}

/// State owned by the worker thread.
struct Worker {
    client: Client,
    activity: PadActivity,
    menu_profile: PathBuf,
    game_profile: Option<PathBuf>,
    mode: InputMode,
    /// Composite devices Hearth has set up.
    devices: BTreeSet<String>,
    /// Composite devices without inputs whose virtual devices were removed.
    ignored: BTreeSet<String>,
    /// Handed back (Hearth is exiting): never take a controller again.
    released: bool,
    state: PadState,
    pressed: Vec<&'static str>,
}

impl Worker {
    fn run(mut self, rx: &Receiver<Msg>, tx: &Sender<Action>) {
        let mut out = Vec::new();
        let mut refreshed = Instant::now();
        loop {
            let now = Instant::now();
            let wait = self.state.deadline().map_or(IDLE_WAIT, |d| {
                d.saturating_duration_since(now).min(IDLE_WAIT)
            });
            match rx.recv_timeout(wait) {
                Ok(Msg::Input(name, value)) => self.on_input(&name, value, &mut out),
                Ok(Msg::Command(command)) => self.on_command(command),
                Ok(Msg::Devices) => self.refresh_devices(),
                Err(RecvTimeoutError::Timeout) => {}
                Err(RecvTimeoutError::Disconnected) => return,
            }
            let now = Instant::now();
            if now >= refreshed + DEVICES_REFRESH {
                self.refresh_devices();
                refreshed = now;
            }
            self.state.tick(now, &mut out);
            for action in out.drain(..) {
                if tx.send(action).is_err() {
                    tracing::debug!("action receiver dropped; stopping InputPlumber thread");
                    return;
                }
            }
        }
    }

    fn on_input(&mut self, name: &str, value: f64, out: &mut Vec<Action>) {
        let down = value > 0.5;
        tracing::trace!(name, down, "InputPlumber event");
        if name == CAPTURE_EVENT {
            // Only bound while a game runs; fires on release like every menu button.
            if !down {
                out.push(Action::Capture);
            }
            return;
        }
        let Some(position) = position_of(name) else {
            return;
        };
        let event = if down {
            if !self.pressed.contains(&position) {
                self.pressed.push(position);
            }
            PadEvent::Pressed(position)
        } else {
            self.pressed.retain(|p| *p != position);
            PadEvent::Released(position)
        };
        self.activity.set_pressed(self.pressed.clone());
        let capture = self.activity.capture_inputs();
        self.state.handle(
            event,
            Instant::now(),
            self.activity.disarm_count(),
            &capture,
            out,
        );
    }

    fn on_command(&mut self, command: InputCommand) {
        match command {
            InputCommand::Mode(mode) => {
                self.mode = mode;
                if mode == InputMode::Shell {
                    // Whatever the game held is gone; menus start from nothing held.
                    self.pressed.clear();
                    self.activity.set_pressed(Vec::new());
                }
                for device in self.devices.clone() {
                    self.apply(&device);
                }
            }
            InputCommand::GameProfile(profile) => self.game_profile = profile,
            InputCommand::Release(done) => {
                tracing::info!("handing the controllers back to InputPlumber");
                self.released = true;
                release_devices(&self.client, &self.devices);
                if let Err(err) = self.client.set_manage_all(false) {
                    tracing::warn!("releasing external controllers failed: {err}");
                }
                let _ = done.send(());
            }
        }
    }

    /// Sets up controllers that appeared, forgets those that went away, refreshes pad info.
    fn refresh_devices(&mut self) {
        if self.released {
            return;
        }
        let current: BTreeSet<String> = match self.client.composite_devices() {
            Ok(devices) => devices.into_iter().collect(),
            Err(err) => {
                tracing::warn!("listing InputPlumber devices failed: {err}");
                return;
            }
        };
        // Devices without inputs are checked again each time: they may gain sources.
        let current: BTreeSet<String> = current
            .into_iter()
            .filter(|device| self.devices.contains(device) || self.has_inputs(device))
            .collect();
        for device in current.difference(&self.devices) {
            tracing::info!(%device, "taking controller");
            if let Err(err) = self.client.set_targets(device, &[VIRTUAL_PAD]) {
                tracing::warn!(%device, "setting the virtual pad failed: {err}");
            }
            self.apply(device);
        }
        if current.len() < self.devices.len() {
            // A controller went away: drop anything it held.
            self.state = PadState::default();
            self.pressed.clear();
            self.activity.set_pressed(Vec::new());
        }
        self.devices = current;
        let pads = self
            .devices
            .iter()
            .filter_map(|device| match self.client.source_pad(device) {
                Ok(pad) => Some(pad),
                Err(err) => {
                    tracing::debug!(%device, "reading the physical pad failed: {err}");
                    None
                }
            })
            .collect();
        self.activity.set_pads(pads);
    }

    /// Whether a composite device produces any input. One that doesn't (only blocked sources,
    /// see [`Client::capabilities`]) must not get a virtual pad: games would see a dead second
    /// controller. Its targets are removed.
    fn has_inputs(&mut self, device: &str) -> bool {
        match self.client.capabilities(device) {
            Ok(caps) if !caps.is_empty() => true,
            Ok(_) => {
                if self.ignored.insert(device.to_owned()) {
                    tracing::info!(%device, "composite device without inputs; removing its virtual devices");
                    if let Err(err) = self.client.set_targets(device, &[]) {
                        tracing::warn!(%device, "removing its virtual devices failed: {err}");
                    }
                }
                false
            }
            Err(err) => {
                tracing::debug!(%device, "reading capabilities failed: {err}");
                false
            }
        }
    }

    /// Puts a controller in the current mode, profile first so a game never sees a press
    /// through the wrong profile.
    fn apply(&self, device: &str) {
        let result = match self.mode {
            InputMode::Shell => self
                .client
                .set_intercept_mode(device, InterceptMode::Always)
                .and_then(|()| self.client.load_profile(device, &self.menu_profile)),
            InputMode::Game => {
                let profile = self
                    .game_profile
                    .as_deref()
                    .unwrap_or(Path::new(client::DEFAULT_PROFILE));
                self.client
                    .load_profile(device, profile)
                    .and_then(|()| self.client.set_intercept_mode(device, InterceptMode::Pass))
            }
        };
        match result {
            Ok(()) => tracing::debug!(%device, mode = ?self.mode, "controller mode set"),
            Err(err) => {
                tracing::warn!(%device, mode = ?self.mode, "setting the controller mode failed: {err}")
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_ui_event_has_a_position() {
        for event in [
            "ui_accept",
            "ui_back",
            "ui_action",
            "ui_context",
            "ui_l1",
            "ui_r1",
            "ui_l2",
            "ui_r2",
            "ui_l3",
            "ui_r3",
            "ui_option",
            "ui_select",
            "ui_guide",
            "ui_up",
            "ui_down",
            "ui_left",
            "ui_right",
            "ui_volume_mute",
            TOUCHPAD_EVENT,
        ] {
            assert!(position_of(event).is_some(), "{event}");
        }
        assert_eq!(position_of("ui_quick"), None);
        assert_eq!(position_of(CAPTURE_EVENT), None);
    }

    #[test]
    fn menu_profile_routes_the_touchpad_to_hearth() {
        assert!(MENU_PROFILE.contains(&format!("dbus: {TOUCHPAD_EVENT}")));
        assert!(MENU_PROFILE.contains("kind: DeviceProfile"));
    }
}
