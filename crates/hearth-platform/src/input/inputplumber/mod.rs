/// The one virtual controller games see: an Xbox Elite 2 pad, whose four paddles and Share
/// button carry emulator actions (SDL and RetroArch both see them).
pub const VIRTUAL_PAD: &str = "xbox-elite";
/// D-Bus event names Hearth's profiles send for inputs InputPlumber has no `ui_*` name for.
pub const TOUCHPAD_EVENT: &str = "hearth_touchpad";
/// Sent while a game runs by the button bound to Hearth's Capture.
pub const CAPTURE_EVENT: &str = "hearth_capture";

/// Hearth's menu profile: buttons unchanged, the touchpad click and Mute sent to Hearth (over
/// D-Bus InputPlumber drops the touchpad otherwise; both go to Hearth in the button test's Pass
/// mode too). Loaded whenever Hearth is in front, so a game's remapping never changes Hearth's
/// own buttons.
pub const MENU_PROFILE: &str = "\
# Generated by Hearth: its menus, every button unchanged.
version: 1
kind: DeviceProfile
name: Hearth menus
mapping:
  - name: Touchpad click
    source_event:
      touchpad:
        name: CenterPad
        touch:
          button: Press
    target_events:
      - dbus: hearth_touchpad
  - name: Mute
    source_event:
      gamepad:
        button: Mute
    target_events:
      - dbus: ui_volume_mute
";

/// Longest sleep without an event or a pending deadline.
const IDLE_WAIT: Duration = Duration::from_millis(250);
/// How often controllers are listed again (battery, missed signals).
const DEVICES_REFRESH: Duration = Duration::from_secs(10);
/// Wait after a controller appears or goes before looking, so its parts have arrived.
const DEVICES_SETTLE: Duration = Duration::from_millis(300);
/// How long InputPlumber may be gone before it counts as stopped rather than restarting.
const RESTART_WAIT: Duration = Duration::from_secs(8);
const SIGNAL_QUEUE: NonZeroUsize = NonZeroUsize::new(64).unwrap();
const OWNER_QUEUE: NonZeroUsize = NonZeroUsize::new(8).unwrap();

/// Controller input via InputPlumber, on its own thread.
#[derive(Debug)]
pub struct InputPlumberBackend {
    client: Client,
    activity: PadActivity,
    menu_profile: PathBuf,
    control: InputControl,
    pending: Option<Receiver<InputCommand>>,
}

impl InputPlumberBackend {
    /// Connects to the daemon and takes the controllers (`ManageAllDevices`). Fails if the
    /// daemon isn't running, is too old, or refuses the write (polkit). `runtime_dir` receives
    /// the menu profile (the root daemon reads it from there).
    pub fn connect(runtime_dir: &Path) -> Result<Self, ClientError> {
        let client = Client::connect()?;
        let menu_profile = runtime_dir.join("menu.yaml");
        std::fs::create_dir_all(runtime_dir)
            .and_then(|()| std::fs::write(&menu_profile, MENU_PROFILE))
            .map_err(|err| ClientError::DBus(format!("writing the menu profile: {err}")))?;
        client.set_manage_all(true)?;
        let (commands, pending) = mpsc::channel();
        Ok(Self {
            client,
            activity: PadActivity::new(),
            menu_profile,
            control: InputControl::new(commands),
            pending: Some(pending),
        })
    }

    /// Live controller state (connected pads, held inputs).
    pub fn activity(&self) -> PadActivity {
        self.activity.clone()
    }

    /// The session's handle: mode switches, game profiles, release on exit.
    pub fn control(&self) -> InputControl {
        self.control.clone()
    }
}

impl InputBackend for InputPlumberBackend {
    fn start(&mut self, tx: Sender<Action>) -> Result<(), InputError> {
        let commands = self.pending.take().ok_or(InputError::AlreadyStarted)?;
        let (msg_tx, msg_rx) = mpsc::channel();
        // Signals first, so no controller created from now on is missed.
        let (signals, owners) =
            subscribe(&self.client).map_err(|err| InputError::Start(err.to_string()))?;
        let signal_tx = msg_tx.clone();
        thread::Builder::new()
            .name("hearth-ip-signals".into())
            .spawn(move || forward_signals(signals, &signal_tx))
            .map_err(|err| InputError::Start(err.to_string()))?;
        let owner_tx = msg_tx.clone();
        thread::Builder::new()
            .name("hearth-ip-owner".into())
            .spawn(move || forward_owner_changes(owners, &owner_tx))
            .map_err(|err| InputError::Start(err.to_string()))?;
        thread::Builder::new()
            .name("hearth-ip-commands".into())
            .spawn(move || {
                for command in commands {
                    if msg_tx.send(Msg::Command(command)).is_err() {
                        return;
                    }
                }
            })
            .map_err(|err| InputError::Start(err.to_string()))?;
        let mut worker = Worker {
            client: self.client.clone(),
            activity: self.activity.clone(),
            menu_profile: self.menu_profile.clone(),
            control: self.control.clone(),
            daemon: Daemon::Up,
            gilrs: None,
            keep_direct: false,
            daemon_present: true,
            game_profile: None,
            mode: InputMode::Shell,
            devices: BTreeSet::new(),
            released: false,
            state: PadState::default(),
            pressed: Vec::new(),
        };
        worker.refresh_devices();
        thread::Builder::new()
            .name("hearth-inputplumber".into())
            .spawn(move || worker.run(&msg_rx, &tx))
            .map_err(|err| InputError::Start(err.to_string()))?;
        Ok(())
    }
}

/// Hands every controller back to the system: input to its virtual pad, default profile, and
/// external controllers released (`ManageAllDevices` off). Uses its own connection, so it works
/// from a panic hook or another process (the guard) whatever state the backend is in.
pub fn release_all() -> Result<(), ClientError> {
    let client = Client::connect()?;
    release_devices(&client, &client.composite_devices()?);
    client.set_manage_all(false)
}

fn release_devices<'a>(client: &Client, devices: impl IntoIterator<Item = &'a String>) {
    for device in devices {
        if let Err(err) = client.release(device) {
            tracing::warn!(%device, "handing the controller back failed: {err}");
        }
    }
}

/// Hands the controllers back if the thread holding it unwinds.
struct ReleaseOnPanic;

impl Drop for ReleaseOnPanic {
    fn drop(&mut self) {
        if thread::panicking() {
            tracing::error!("InputPlumber thread panicked; handing the controllers back");
            if let Err(err) = release_all() {
                tracing::warn!("handing the controllers back failed: {err}");
            }
        }
    }
}

/// Everything the worker thread reacts to.
#[derive(Debug)]
enum Msg {
    Command(InputCommand),
    /// `InputEvent(name, value)` from a D-Bus target.
    Input(String, f64),
    /// Composite devices were added or removed.
    Devices,
    /// This composite device was (re)created: a controller reconnecting gets the path it had.
    Added(String),
    /// The daemon got (`true`) or lost (`false`) its bus name: it restarted or stopped.
    Owner(bool),
}

/// Every signal under the daemon's objects (input events, devices coming and going), and its
/// bus name changing owner. By path rather than by sender, so a restarted daemon (a new unique
/// name) still matches.
fn subscribe(client: &Client) -> Result<(MessageStream, MessageStream), zbus::Error> {
    let objects = MatchRule::builder()
        .msg_type(MessageType::Signal)
        .path_namespace("/org/shadowblip/InputPlumber")
        .build()?;
    let owner = MatchRule::builder()
        .msg_type(MessageType::Signal)
        .sender("org.freedesktop.DBus")
        .interface("org.freedesktop.DBus")
        .member("NameOwnerChanged")
        .arg(0, SERVICE)
        .build()?;
    Ok((
        zbus::block_on(MessageStream::for_match_rule(
            objects,
            client.connection(),
            Some(SIGNAL_QUEUE),
        ))?,
        zbus::block_on(MessageStream::for_match_rule(
            owner,
            client.connection(),
            Some(OWNER_QUEUE),
        ))?,
    ))
}

fn forward_owner_changes(mut changes: MessageStream, tx: &Sender<Msg>) {
    while let Some(message) = zbus::block_on(std::future::poll_fn(|cx| {
        Pin::new(&mut changes).poll_next(cx)
    })) {
        let Ok(message) = message else {
            continue;
        };
        let Ok((name, _old, new)) = message.body().deserialize::<(String, String, String)>() else {
            continue;
        };
        if name == SERVICE && tx.send(Msg::Owner(!new.is_empty())).is_err() {
            return;
        }
    }
}

fn forward_signals(mut signals: MessageStream, tx: &Sender<Msg>) {
    while let Some(message) = zbus::block_on(std::future::poll_fn(|cx| {
        Pin::new(&mut signals).poll_next(cx)
    })) {
        let Ok(message) = message else {
            continue;
        };
        let header = message.header();
        let (Some(interface), Some(member)) = (header.interface(), header.member()) else {
            continue;
        };
        let msg = match (interface.as_str(), member.as_str()) {
            ("org.shadowblip.Input.DBusDevice", "InputEvent") => {
                match message.body().deserialize::<(String, f64)>() {
                    Ok((name, value)) => Msg::Input(name, value),
                    Err(err) => {
                        tracing::debug!("bad InputEvent: {err}");
                        continue;
                    }
                }
            }
            // Source and target objects come and go all the time; only controllers matter.
            ("org.freedesktop.DBus.ObjectManager", "InterfacesAdded") => {
                match message
                    .body()
                    .deserialize::<(OwnedObjectPath, AddedInterfaces)>()
                {
                    Ok((path, _)) if is_composite_path(path.as_str()) => {
                        Msg::Added(path.to_string())
                    }
                    _ => continue,
                }
            }
            ("org.freedesktop.DBus.ObjectManager", "InterfacesRemoved") => {
                match message
                    .body()
                    .deserialize::<(OwnedObjectPath, Vec<String>)>()
                {
                    Ok((path, _)) if is_composite_path(path.as_str()) => Msg::Devices,
                    _ => continue,
                }
            }
            _ => continue,
        };
        if tx.send(msg).is_err() {
            return;
        }
    }
    tracing::warn!("InputPlumber signal stream ended");
}

/// The interfaces (with their properties) in an `InterfacesAdded` signal.
type AddedInterfaces = HashMap<String, HashMap<String, OwnedVariant>>;

/// Whether an object path is a composite device (`…/CompositeDevice3`).
fn is_composite_path(path: &str) -> bool {
    path.strip_prefix("/org/shadowblip/InputPlumber/CompositeDevice")
        .is_some_and(|n| !n.is_empty() && n.bytes().all(|b| b.is_ascii_digit()))
}

/// Hearth pad position name of an InputPlumber D-Bus event. D-pad and left stick both send
/// `ui_up`… (InputPlumber merges them), so both count as the D-pad here.
fn position_of(event: &str) -> Option<&'static str> {
    Some(match event {
        "ui_accept" => "south",
        "ui_back" => "east",
        "ui_action" => "west",
        "ui_context" => "north",
        "ui_l1" => "l1",
        "ui_r1" => "r1",
        "ui_l2" => "l2",
        "ui_r2" => "r2",
        "ui_l3" => "l3",
        "ui_r3" => "r3",
        "ui_option" => "start",
        "ui_select" => "select",
        "ui_guide" => "guide",
        "ui_up" => "dpad_up",
        "ui_down" => "dpad_down",
        "ui_left" => "dpad_left",
        "ui_right" => "dpad_right",
        "ui_volume_mute" => "mute",
        TOUCHPAD_EVENT => "touchpad",
        _ => return None,
    })
}

/// Whether the daemon is there.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Daemon {
    Up,
    /// Gone since then: no calls (they would only fail), gilrs reads the controllers, and
    /// whether [`InputStatus::StillLost`] was reported.
    Down(Instant, bool),
}

/// State owned by the worker thread.
struct Worker {
    client: Client,
    activity: PadActivity,
    menu_profile: PathBuf,
    control: InputControl,
    daemon: Daemon,
    /// Stops the gilrs thread reading controllers while the daemon is gone.
    gilrs: Option<Arc<AtomicBool>>,
    /// A running game reads the physical controller ([`InputCommand::KeepDirect`]).
    keep_direct: bool,
    /// The daemon has its bus name again (it may be waiting for `keep_direct` to end).
    daemon_present: bool,
    game_profile: Option<PathBuf>,
    mode: InputMode,
    /// Composite devices Hearth has set up.
    devices: BTreeSet<String>,
    /// Handed back (Hearth is exiting): never take a controller again.
    released: bool,
    state: PadState,
    pressed: Vec<&'static str>,
}

impl Worker {
    fn run(mut self, rx: &Receiver<Msg>, tx: &Sender<Action>) {
        // Without this thread nothing reads the controllers: if it panics, hand them back.
        let _release_on_panic = ReleaseOnPanic;
        let mut out = Vec::new();
        // When to list the controllers again: soon after a change (InputPlumber adds a
        // controller's parts one by one), and every DEVICES_REFRESH anyway.
        let mut refresh_at = Instant::now() + DEVICES_REFRESH;
        loop {
            let now = Instant::now();
            let deadline = self
                .state
                .deadline()
                .map_or(refresh_at, |d| d.min(refresh_at));
            let wait = deadline.saturating_duration_since(now).min(IDLE_WAIT);
            match rx.recv_timeout(wait) {
                Ok(Msg::Command(command)) => self.on_command(command),
                Ok(Msg::Input(name, value)) => self.on_input(&name, value, &mut out),
                Ok(Msg::Devices) => refresh_at = refresh_at.min(now + DEVICES_SETTLE),
                Ok(Msg::Added(device)) => {
                    // A new device even if the path is known: set it up again.
                    self.devices.remove(&device);
                    refresh_at = refresh_at.min(now + DEVICES_SETTLE);
                }
                Ok(Msg::Owner(false)) => {
                    self.daemon_present = false;
                    self.daemon_gone(now, tx);
                }
                Ok(Msg::Owner(true)) => {
                    self.daemon_present = true;
                    if self.daemon_back() {
                        // Its controllers appear over the next second (signals follow too).
                        refresh_at = now + DEVICES_SETTLE;
                    }
                }
                Err(RecvTimeoutError::Timeout) => {}
                Err(RecvTimeoutError::Disconnected) => return,
            }
            let now = Instant::now();
            if let Daemon::Down(since, false) = self.daemon
                && now >= since + RESTART_WAIT
            {
                tracing::warn!("InputPlumber is still gone");
                self.daemon = Daemon::Down(since, true);
                self.control.report(InputStatus::StillLost);
            }
            if now >= refresh_at {
                self.refresh_devices();
                refresh_at = now + DEVICES_REFRESH;
            }
            self.state.tick(now, &mut out);
            for action in out.drain(..) {
                if tx.send(action).is_err() {
                    tracing::debug!("action receiver dropped; stopping InputPlumber thread");
                    return;
                }
            }
        }
    }

    fn on_input(&mut self, name: &str, value: f64, out: &mut Vec<Action>) {
        let down = value > 0.5;
        tracing::trace!(name, down, "InputPlumber event");
        if name == CAPTURE_EVENT {
            // Only bound while a game runs; fires on release like every menu button.
            if !down {
                out.push(Action::Capture);
            }
            return;
        }
        let Some(position) = position_of(name) else {
            return;
        };
        if position == "guide" && !down && self.mode == InputMode::Test {
            // Guide switched the controller to Hearth by itself; the test reads the virtual pad.
            for device in self.devices.clone() {
                self.apply(&device);
            }
        }
        let event = if down {
            if !self.pressed.contains(&position) {
                self.pressed.push(position);
            }
            PadEvent::Pressed(position)
        } else {
            self.pressed.retain(|p| *p != position);
            PadEvent::Released(position)
        };
        self.activity.set_pressed(self.pressed.clone());
        let capture = self.activity.capture_inputs();
        self.state.handle(
            event,
            Instant::now(),
            self.activity.disarm_count(),
            &capture,
            out,
        );
    }

    /// InputPlumber lost its bus name. Its controllers and virtual pads went with it, and the
    /// raw controllers are back: gilrs reads them until it returns, so Hearth stays usable.
    fn daemon_gone(&mut self, now: Instant, tx: &Sender<Action>) {
        if self.daemon != Daemon::Up {
            return;
        }
        tracing::warn!("InputPlumber went away; reading controllers with gilrs until it is back");
        self.daemon = Daemon::Down(now, false);
        self.devices.clear();
        self.state = PadState::default();
        self.pressed.clear();
        self.activity.set_pressed(Vec::new());
        self.activity.set_pads(Vec::new());
        let mut gilrs = super::gilrs::GilrsBackend::with_activity(self.activity.clone());
        match gilrs.start(tx.clone()) {
            // Its thread keeps running until stopped.
            Ok(()) => self.gilrs = Some(gilrs.stopper()),
            Err(err) => tracing::error!("starting gilrs failed, keyboard only: {err}"),
        }
        self.control.report(InputStatus::Lost);
    }

    /// InputPlumber has its bus name again: take the controllers back. The device refresh that
    /// follows sets the virtual pad, the current profile and mode, and strips duplicates.
    /// Returns whether it worked (if not, gilrs keeps going until the next time it starts).
    fn daemon_back(&mut self) -> bool {
        if self.daemon == Daemon::Up {
            return true;
        }
        if self.keep_direct {
            tracing::info!("InputPlumber is back; waiting for the game started without it to end");
            return false;
        }
        let taken = self.client.version().and_then(|version| {
            tracing::info!(%version, "InputPlumber is back; taking the controllers again");
            self.client.set_manage_all(true)
        });
        if let Err(err) = taken {
            tracing::warn!("InputPlumber came back but refused the controllers: {err}");
            return false;
        }
        if let Some(stop) = self.gilrs.take() {
            stop.store(true, Ordering::Release);
        }
        self.daemon = Daemon::Up;
        self.control.report(InputStatus::Back);
        true
    }

    fn on_command(&mut self, command: InputCommand) {
        tracing::debug!(?command, "input command");
        if let InputCommand::KeepDirect(keep) = command {
            self.keep_direct = keep;
            if !keep && self.daemon_present {
                self.daemon_back();
            }
            return;
        }
        if self.daemon != Daemon::Up {
            // Remember the mode and profile for when the daemon is back; nothing to call now.
            match command {
                InputCommand::Mode(mode) => self.mode = mode,
                InputCommand::GameProfile(profile) => self.game_profile = profile,
                InputCommand::Release(done) => {
                    self.released = true;
                    let _ = done.send(());
                }
                // Handled above.
                InputCommand::KeepDirect(_) => {}
            }
            return;
        }
        match command {
            InputCommand::Mode(mode) => {
                self.mode = mode;
                if mode == InputMode::Shell {
                    // Whatever the game held is gone; menus start from nothing held.
                    self.pressed.clear();
                    self.activity.set_pressed(Vec::new());
                }
                for device in self.devices.clone() {
                    self.apply(&device);
                }
            }
            InputCommand::GameProfile(profile) => self.game_profile = profile,
            // Handled above.
            InputCommand::KeepDirect(_) => {}
            InputCommand::Release(done) => {
                tracing::info!("handing the controllers back to InputPlumber");
                self.released = true;
                release_devices(&self.client, &self.devices);
                if let Err(err) = self.client.set_manage_all(false) {
                    tracing::warn!("releasing external controllers failed: {err}");
                }
                let _ = done.send(());
            }
        }
    }

    /// Sets up controllers that appeared, forgets those that went away, refreshes pad info.
    fn refresh_devices(&mut self) {
        if self.released || self.daemon != Daemon::Up {
            return;
        }
        let current: BTreeSet<String> = match self.client.composite_devices() {
            Ok(devices) => devices.into_iter().collect(),
            Err(err) => {
                tracing::warn!("listing InputPlumber devices failed: {err}");
                return;
            }
        };
        // Devices without inputs are checked again each time: they may gain sources.
        let current: BTreeSet<String> = current
            .into_iter()
            .filter(|device| self.devices.contains(device) || self.has_inputs(device))
            .collect();
        for device in current.difference(&self.devices) {
            tracing::info!(%device, "taking controller");
            if let Err(err) = self.client.set_targets(device, &[VIRTUAL_PAD]) {
                tracing::warn!(%device, "setting the virtual pad failed: {err}");
            }
            self.apply(device);
        }
        if current.len() < self.devices.len() {
            // A controller went away: drop anything it held.
            self.state = PadState::default();
            self.pressed.clear();
            self.activity.set_pressed(Vec::new());
        }
        self.devices = current;
        let pads = self
            .devices
            .iter()
            .filter_map(|device| match self.client.source_pad(device) {
                Ok(pad) => Some(pad),
                Err(err) => {
                    tracing::debug!(%device, "reading the physical pad failed: {err}");
                    None
                }
            })
            .collect();
        self.activity.set_pads(pads);
    }

    /// Whether a composite device produces any input. One that doesn't (only blocked sources,
    /// see [`Client::capabilities`]) must not get a virtual pad: games would see a dead second
    /// controller (with Hearth's InputPlumber config it even gets the Elite pad games are
    /// allowed to see). Its targets are removed, again whenever it has some: a reconnecting
    /// controller brings new ones at the same paths.
    fn has_inputs(&mut self, device: &str) -> bool {
        match self.client.capabilities(device) {
            Ok(caps) if !caps.is_empty() => true,
            Ok(_) => {
                let has_targets = self.client.targets(device).is_ok_and(|t| !t.is_empty());
                if has_targets {
                    tracing::info!(%device, "composite device without inputs; removing its virtual devices");
                    if let Err(err) = self.client.set_targets(device, &[]) {
                        tracing::warn!(%device, "removing its virtual devices failed: {err}");
                    }
                }
                false
            }
            Err(err) => {
                tracing::debug!(%device, "reading capabilities failed: {err}");
                false
            }
        }
    }

    /// Puts a controller in the current mode, profile first so a game never sees a press
    /// through the wrong profile.
    fn apply(&self, device: &str) {
        let result = match self.mode {
            InputMode::Test => self
                .client
                .load_profile(device, &self.menu_profile)
                .and_then(|()| self.client.set_intercept_mode(device, InterceptMode::Pass)),
            InputMode::Shell => self
                .client
                .set_intercept_mode(device, InterceptMode::Always)
                .and_then(|()| self.client.load_profile(device, &self.menu_profile)),
            InputMode::Game => {
                let profile = self
                    .game_profile
                    .as_deref()
                    .unwrap_or(Path::new(client::DEFAULT_PROFILE));
                self.client
                    .load_profile(device, profile)
                    .and_then(|()| self.client.set_intercept_mode(device, InterceptMode::Pass))
            }
        };
        match result {
            Ok(()) => tracing::debug!(%device, mode = ?self.mode, "controller mode set"),
            Err(err) => {
                tracing::warn!(%device, mode = ?self.mode, "setting the controller mode failed: {err}")
            }
        }
    }
}

