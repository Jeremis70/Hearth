#!/usr/bin/env python3
"""Builds assets/controllers/generic.svg from assets/controllers/source/gamepad.svg.

Keeps the body and the input shapes, drops the baked-in leader lines, labels and the face
buttons' arrow marks, gives each input a Hearth id and restyles everything as line art for
Slint's `colorize` (every pixel's alpha is kept, its color replaced): strokes are opaque, fills
are white at low opacity so they become a faint tint of the same theme color.

Usage: scripts/controller-svg.py [source.svg] [out.svg]
Then regenerate the anchors: cargo run -p hearth-shell --example controller_anchors
"""

import re
import sys

SOURCE = "assets/controllers/source/gamepad.svg"
OUT = "assets/controllers/generic.svg"

# Hearth id -> source element ids (first one is the input's outline).
INPUTS = {
    "l2": ["path30"],
    "r2": ["path190"],
    "l1": ["path28"],
    "r1": ["path191"],
    "dpad_up": ["path31", "path35"],
    "dpad_down": ["path53", "path54"],
    "dpad_left": ["path172", "path188"],
    "dpad_right": ["path57", "path58"],
    "face_north": ["circle231"],
    "face_south": ["circle230"],
    "face_west": ["circle200"],
    "face_east": ["circle229"],
    # Sticks: the ring (stick movement) and the cap (stick click) are separate inputs.
    "ls": ["circle188", "circle189"],
    "l3": ["circle189"],
    "rs": ["circle198", "circle199"],
    "r3": ["circle199"],
    "select": ["circle190"],
    "start": ["circle197"],
}
# Shapes drawn over the body's outline: the outline is masked out under them.
OVER_BODY = ["l1", "r1"]
# Rings: the outer circle with the next one cut out (even-odd), so the cap is its own shape.
RINGS = {"ls", "rs"}
# Small filled marks (the D-pad arrows) stay solid.
MARKS = {"path35", "path54", "path188", "path58"}

STROKE = 0.85  # drawing units; the page draws the 141.55-unit height at 520 px (1080p): ~3 px
FILL_OPACITY = 0.06


def element(src, eid):
    match = re.search(r"<(path|circle|rect)\s[^>]*?\bid=\"%s\"[^>]*/>" % re.escape(eid), src, re.S)
    if not match:
        sys.exit(f"{eid} not found in the source")
    tag = match.group(1)
    attrs = dict(re.findall(r"([\w:-]+)=\"([^\"]*)\"", match.group(0)))
    keep = {"path": ["d", "transform"], "circle": ["cx", "cy", "r"], "rect": []}[tag]
    return tag, {k: attrs[k] for k in keep if k in attrs}


def circle_path(attrs):
    cx, cy, r = (float(attrs[k]) for k in ("cx", "cy", "r"))
    return (f"M {cx - r:g} {cy:g} A {r:g} {r:g} 0 1 0 {cx + r:g} {cy:g} "
            f"A {r:g} {r:g} 0 1 0 {cx - r:g} {cy:g} Z")


def render(tag, attrs, style):
    body = " ".join(f'{k}="{v}"' for k, v in attrs.items())
    return f'<{tag} {body} {style}/>'


def main():
    src_path = sys.argv[1] if len(sys.argv) > 1 else SOURCE
    out_path = sys.argv[2] if len(sys.argv) > 2 else OUT
    src = open(src_path, encoding="utf-8").read()
    view = re.search(r'viewBox="([^"]+)"', src).group(1).split()
    width, height = float(view[2]), float(view[3])
    offset = re.search(r'id="layer1"\s+transform="translate\(([-\d.]+),([-\d.]+)\)"', src)
    dx, dy = offset.group(1), offset.group(2)

    line = f'fill="#fff" fill-opacity="{FILL_OPACITY}" stroke="#fff"'
    mark = 'fill="#fff" stroke="none"'

    groups = []
    for hid, ids in INPUTS.items():
        parts = []
        if hid in RINGS:
            outer, inner = (element(src, eid)[1] for eid in ids)
            d = circle_path(outer) + " " + circle_path(inner)
            groups.append(f'  <g id="{hid}">\n    <path d="{d}" fill-rule="evenodd" {line}/>\n  </g>')
            continue
        for eid in ids:
            tag, attrs = element(src, eid)
            parts.append("    " + render(tag, attrs, mark if eid in MARKS else line))
        groups.append(f'  <g id="{hid}">\n' + "\n".join(parts) + "\n  </g>")

    tag, body = element(src, "path21")
    covers = []
    for hid in OVER_BODY:
        for eid in INPUTS[hid]:
            t, attrs = element(src, eid)
            covers.append("      " + render(t, attrs, 'fill="#000" stroke="#000"'))

    out = f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/controller-svg.py from source/gamepad.svg (lambdalighthouse,
     https://lambdalighthouse.itch.io/controller-keyboard-template). Don't edit by hand.
     One color: Slint colorizes it with the theme. Ids are Hearth inputs (face_* by position). -->
<svg xmlns="http://www.w3.org/2000/svg" width="{width:g}" height="{height:g}" viewBox="0 0 {width:g} {height:g}">
<defs>
  <mask id="under-bumpers" maskUnits="userSpaceOnUse" x="{-float(dx):g}" y="{-float(dy):g}" width="{width:g}" height="{height:g}">
    <rect x="{-float(dx):g}" y="{-float(dy):g}" width="{width:g}" height="{height:g}" fill="#fff"/>
{chr(10).join(covers)}
  </mask>
</defs>
<g transform="translate({dx},{dy})" stroke-width="{STROKE}" stroke-linecap="round" stroke-linejoin="round">
  <g id="body" mask="url(#under-bumpers)">
    {render(tag, body, line)}
  </g>
{chr(10).join(groups)}
</g>
</svg>
"""
    open(out_path, "w", encoding="utf-8").write(out)


if __name__ == "__main__":
    main()
